def objs(spec):
    """spec: {id: layer} or {id: (layer, name)} -> expected list in id order"""
    out = []
    for i in sorted(spec):
        v = spec[i]
        layer, name = (v, "") if isinstance(v, str) else v
        out.append((i, K[i] if i in K else "point", layer, name))
    return out
def D(*ids, layer="Default"): return {i: layer for i in ids}
def U(*dicts):
    r = {}
    for d in dicts: r.update(d)
    return r

