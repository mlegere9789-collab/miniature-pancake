#!/usr/bin/env python3
"""Generate tutorials/index.html from the tutorial sources (stdlib only).

The page content (titles, summaries, durations, transcripts) comes only from
<id>/tutorial.txt, so the committed index.html is deterministic.  Videos,
posters and captions are referenced as out/<id>/<id>.{mp4,png,vtt}; they are
produced by record.sh and are not committed.  No scripts, CDN or trackers.
"""
import glob
import html
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import tutlib  # noqa: E402

CSS = """
:root{--bg:#f6f7f9;--fg:#1c2128;--muted:#59636e;--card:#fff;--line:#d0d7de;--acc:#0b6e69}
@media (prefers-color-scheme:dark){:root{--bg:#161b22;--fg:#e6edf3;--muted:#9aa7b4;--card:#1f262e;--line:#30363d;--acc:#4cc2b8}}
*{box-sizing:border-box}
body{margin:0;background:var(--bg);color:var(--fg);font:16px/1.5 system-ui,-apple-system,"Segoe UI",sans-serif}
main{max-width:980px;margin:0 auto;padding:24px 16px 64px}
h1{margin:0 0 4px;font-size:1.8rem}
.lead{color:var(--muted);margin:0 0 24px}
article{background:var(--card);border:1px solid var(--line);border-radius:10px;padding:16px;margin:0 0 24px}
article h2{margin:0;font-size:1.25rem}
.meta{color:var(--muted);font-size:.9rem;margin:2px 0 10px}
video{width:100%;max-width:100%;aspect-ratio:16/9;background:#000;border-radius:6px}
details{margin-top:10px}summary{cursor:pointer;color:var(--acc)}
ol.tr{padding-left:1.4em;margin:8px 0}
ol.tr li{margin:2px 0}ol.tr time{color:var(--muted);font-variant-numeric:tabular-nums;margin-right:6px}
.links a{color:var(--acc);margin-right:14px;font-size:.9rem}
code{background:rgba(127,127,127,.15);padding:0 4px;border-radius:3px}
"""


def mmss(t):
    t = int(t)
    return "%d:%02d" % (t // 60, t % 60)


def main():
    ids = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(HERE, "[0-9][0-9]-*", "tutorial.txt")))
    out = []
    total = 0.0
    for i in ids:
        meta, items = tutlib.parse(os.path.join(HERE, i, "tutorial.txt"))
        tl = tutlib.build_timeline(items)
        total += tl["duration"]
        e = html.escape
        out.append('<article id="%s">' % e(i))
        out.append("<h2>%s</h2>" % e(meta["title"]))
        out.append('<p class="meta">%s &middot; %s &middot; %d narration cues</p>' % (e(meta["level"]), mmss(tl["duration"]), len(tl["cues"])))
        out.append("<p>%s</p>" % e(meta["summary"]))
        out.append('<video controls preload="none" poster="out/%s/%s.png">' % (e(i), e(i)))
        out.append('<source src="out/%s/%s.mp4" type="video/mp4">' % (e(i), e(i)))
        out.append('<track kind="captions" srclang="en" label="English" src="out/%s/%s.vtt" default>' % (e(i), e(i)))
        out.append("Your browser cannot play this video; the transcript below has the same content.</video>")
        out.append("<details><summary>Transcript</summary><ol class=\"tr\">")
        for c in tl["cues"]:
            out.append("<li><time>%s</time>%s</li>" % (mmss(c["start"]), e(c["text"])))
        out.append("</ol></details>")
        out.append('<p class="links"><a href="%s/tutorial.txt">command script</a>'
                   '<a href="out/%s/%s.vtt">captions (.vtt)</a><a href="out/%s/%s.txt">voice-over script</a></p>' % (e(i), e(i), e(i), e(i), e(i)))
        out.append("</article>")
    page = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Dino 8 video tutorials</title>
<style>%s</style>
</head>
<body>
<main>
<h1>Dino 8 video tutorials</h1>
<p class="lead">%d tutorials, %s in total. Every video is generated by running the real app on the
command script shown next to it, so each step on screen is a command you can type yourself.
Videos are not stored in the repository: run <code>tutorials/record.sh</code> to produce them
(see <code>docs/TUTORIALS.md</code>).</p>
%s
</main>
</body>
</html>
""" % (CSS, len(ids), mmss(total), "\n".join(out))
    with open(os.path.join(HERE, "index.html"), "w", encoding="utf-8", newline="\n") as f:
        f.write(page)
    print("build-site: wrote %s (%d tutorials)" % (os.path.join(HERE, "index.html"), len(ids)))


if __name__ == "__main__":
    main()
