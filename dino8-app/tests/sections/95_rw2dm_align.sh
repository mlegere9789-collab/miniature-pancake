rw2_align_run rw2dm_align_top_script.txt
rw2_align_run rw2dm_align_bottom_script.txt
rw2_align_run rw2dm_align_concentric_script.txt
rw2_align_run rw2dm_align_horiz_script.txt
rw2_align_run rw2dm_align_cp_left_script.txt
rw2_align_run rw2dm_align_cp_region_script.txt
rw2_align_run rw2dm_align_cp_one_script.txt
rw2_align_run rw2dm_align_cp_conc_script.txt
rw2_align_block() { awk -v name="$1" '$0 ~ ("Unknown command: RW2BEGIN_" name "$") { on = 1; next } on && /Unknown command: RW2BEGIN_/ { exit } on { print }' <<<"$RW2_ALIGN_OUT"; }
# rw2_align_resid NAME NPTS BOXES DESC: the case listed exactly NPTS points, every one at residual 0,0,0, and the boxes' bounding boxes (joined by ';') read exactly BOXES
rw2_align_resid() {
  local blk npts zeros boxes; blk="$(rw2_align_block "$1")"
  npts="$({ grep -cE '^history: Object [0-9]+ \(point\)' <<<"$blk" || true; })"
  zeros="$({ grep -cE '^history:   0,0,0$' <<<"$blk" || true; })"
  boxes="$({ grep -E '^history: Bounding box min ' <<<"$blk" || true; } | sed -E 's/^history: Bounding box //' | paste -sd';' -)"
  if [ "$npts" = "$2" ] && [ "$zeros" = "$2" ] && [ "$boxes" = "$3" ]; then echo "ok   RW2DM_ALIGN_$1: $4 ($2 points at residual 0 within 1e-9; boxes: ${3:-none})"
  else echo "FAIL RW2DM_ALIGN_$1: $4 (listed $npts points, $zeros at residual 0, expected $2 and $2; boxes '$boxes', expected '$3')"; fail=1; { grep -E '^history:   |^history: Bounding box|^history: ! ' <<<"$blk" || true; } | head -16 | sed 's/^/     residual: /'; fi
}
rw2_align_resid left 7 "min 0,0,0 max 2,2,2" "Align Left on a point, a line, a plane and a box: every bounding box's minimum x becomes the smallest minimum x (-2); y and z are untouched"
rw2_align_resid right 7 "min 0,0,0 max 2,2,2" "Align Right: every bounding box's maximum x becomes the largest maximum x (10)"
rw2_align_resid top 7 "min 0,0,0 max 2,2,2" "Align Top: every maximum y becomes the largest maximum y (8)"
rw2_align_resid bottom 7 "min 0,0,0 max 2,2,2" "Align Bottom: every minimum y becomes the smallest minimum y (-3)"
rw2_align_resid concentric 7 "min 0,0,0 max 2,2,2" "Align Concentric: every bounding-box centre goes to the centre of the whole set ((lo + hi) / 2 in x and y)"
rw2_align_resid horiz 7 "min 0,0,0 max 2,2,2" "Align HorizCenter: every centre's y becomes the middle of the set's y extent"
rw2_align_resid cp_left 6 "" "Align Left on the 6 selected control points of a line and a plane: every control point's x becomes the smallest x among them (0), y and z kept"
rw2_align_resid cp_region 6 "" "Align Top on three control points picked by SelControlPointRegion (x in 0..3): they all get the largest y among them (8); the other three stay"
rw2_align_resid cp_one 2 "" "Align HorizCenter with ONE object: its two control points (0,0,0) and (6,2,0) both get the middle y = 1"
rw2_align_resid cp_conc 6 "" "Align Concentric on the 6 control points: x and y both go to the middle of the extent: x = 3, y = 4"
# negative control: the same harness must SEE a 1e-6 error (a point 1e-6 off its expected image reads 1e-06, not 0)
rw2_align_sens() {
  local blk; blk="$(rw2_align_block sensitivity)"
  if grep -qE '^history:   (0,0,)?[-0-9.e]*1e-06' <<<"$blk" && ! grep -qE '^history:   0,0,0$' <<<"$blk"; then echo "ok   RW2DM_ALIGN_sensitivity: the residual harness reports a 1e-6 error as 1e-06 (negative control)"
  else echo "FAIL RW2DM_ALIGN_sensitivity: a 1e-6 error was not visible"; fail=1; { grep -E '^history:   ' <<<"$blk" || true; } | head -4 | sed 's/^/     residual: /'; fi
}
