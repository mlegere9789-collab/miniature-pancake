struct Topo {
  MD d;
  std::vector<std::vector<int>> rings;
  std::vector<int> offset;  // first corner index of each ring
  std::vector<std::pair<int, int>> edges;  // sorted distinct vertex pairs (face edges and edges with no face)
  int corners = 0;
};

bool BuildTopo(const Value& v, Topo& t, EvalContext& c, const char* who) {
  const kernel::Mesh* m = MeshOf(v);
  if (!m) { c.Fail(std::string(who) + " needs a mesh"); return false; }
  t.d = ReadMesh(m->raw());
  bool wire = false;
  if (!PolygonRings(t.d, t.rings, wire)) { c.Fail(std::string(who) + " could not read the faces of the mesh"); return false; }
  t.corners = 0;
  t.offset.clear();
  std::set<std::pair<int, int>> es;
  for (const auto& r : t.rings) {
    t.offset.push_back(t.corners);
    t.corners += static_cast<int>(r.size());
    for (size_t i = 0; i < r.size(); ++i) { const int a = r[i], b = r[(i + 1) % r.size()]; es.insert({std::min(a, b), std::max(a, b)}); }
  }
  for (const auto& f : t.d.f) if (IsWire(f)) es.insert({std::min(f[0], f[1]), std::max(f[0], f[1])});
  t.edges.assign(es.begin(), es.end());
  return true;
}

Vector3d RingNormal(const MD& d, const std::vector<int>& ring) {
  Vector3d n(0, 0, 0);
  for (size_t i = 0; i < ring.size(); ++i) {
    const Point3d& a = d.v[static_cast<size_t>(ring[i])];
    const Point3d& b = d.v[static_cast<size_t>(ring[(i + 1) % ring.size()])];
    n.x += (a.y - b.y) * (a.z + b.z); n.y += (a.z - b.z) * (a.x + b.x); n.z += (a.x - b.x) * (a.y + b.y);
  }
  return n;
}

std::vector<double> Numbers(const std::vector<Value>& l) {
  std::vector<double> out;
  for (const Value& v : l) { double x; if (v.AsNumber(x) && std::isfinite(x)) out.push_back(x); }
  return out;
}

struct Stats { double mean = 0, median = 0, sum = 0, mn = 0, mx = 0, range = 0, sd = 0, var = 0; };

Stats Compute(std::vector<double> x) {
  Stats s;
  const double n = static_cast<double>(x.size());
  for (double v : x) s.sum += v;
  s.mean = s.sum / n;
  std::sort(x.begin(), x.end());
  s.mn = x.front(); s.mx = x.back(); s.range = s.mx - s.mn;
  s.median = x[x.size() / 2];
  for (double v : x) s.var += (v - s.mean) * (v - s.mean);
  s.var /= n;
  s.sd = std::sqrt(s.var);
  return s;
}

std::vector<Value> IntList(const std::vector<int>& v) {
  std::vector<Value> out;
  for (int x : v) out.push_back(Value::Integer(x));
  return out;
}

void AddTopology() {
  Registry& r = Registry::Get();
  {
    NodeDef d; d.name = "Corners of Face"; d.nick = "CornFace"; d.category = kCat; d.subcategory = "Mesh Topology";
    d.description = "The corners of one face. Corners are numbered face by face in face order (a triangle has 3, a quad 4, an n-gon one per boundary vertex), so the first corner of face f is the number of corners of the faces before it. Corner Index lists the face's corners in order; Total is their count. Sorting by weights is not modelled.";
    d.inputs = {In("Mesh", Kind::Mesh), In("Face Index", Kind::Integer, Access::Item, Value::Integer(0))};
    d.outputs = {Out("Corner Index", Kind::Integer), Out("Total", Kind::Integer)};
    d.eval = [](EvalContext& c) {
      Topo t;
      if (!BuildTopo(c.In(0), t, c, "Corners of Face")) return;
      const int f = c.Int(1, 0);
      if (f < 0 || f >= static_cast<int>(t.rings.size())) { c.Warn("Face Index is outside the mesh"); c.OutList(0, {}); c.Out(1, Value::Integer(0)); return; }
      std::vector<int> out;
      for (size_t i = 0; i < t.rings[static_cast<size_t>(f)].size(); ++i) out.push_back(t.offset[static_cast<size_t>(f)] + static_cast<int>(i));
      c.OutList(0, IntList(out));
      c.Out(1, Value::Integer(static_cast<long long>(out.size())));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Face of Corner"; d.nick = "FaceCorn"; d.category = kCat; d.subcategory = "Mesh Topology";
    d.description = "The face a corner belongs to and the corner's position inside that face (0 for the first corner of the face). Corners are numbered as in Corners of Face; a corner number outside the mesh gives 0 and 0 with a warning.";
    d.inputs = {In("Mesh", Kind::Mesh), In("Corner Index", Kind::Integer, Access::Item, Value::Integer(0))};
    d.outputs = {Out("Face Index", Kind::Integer), Out("Index in Face", Kind::Integer)};
    d.eval = [](EvalContext& c) {
      Topo t;
      if (!BuildTopo(c.In(0), t, c, "Face of Corner")) return;
      const int k = c.Int(1, 0);
      if (k < 0 || k >= t.corners) { c.Warn("Corner Index is outside the mesh"); c.Out(0, Value::Integer(0)); c.Out(1, Value::Integer(0)); return; }
      size_t f = 0;
      while (f + 1 < t.rings.size() && t.offset[f + 1] <= k) ++f;
      c.Out(0, Value::Integer(static_cast<long long>(f)));
      c.Out(1, Value::Integer(k - t.offset[f]));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Vertex of Corner"; d.nick = "VertCorn"; d.category = kCat; d.subcategory = "Mesh Topology";
    d.description = "The vertex a corner sits on. Corners are numbered as in Corners of Face; a corner number outside the mesh gives 0 with a warning.";
    d.inputs = {In("Mesh", Kind::Mesh), In("Corner Index", Kind::Integer, Access::Item, Value::Integer(0))};
    d.outputs = {Out("Vertex Index", Kind::Integer)};
    d.eval = [](EvalContext& c) {
      Topo t;
      if (!BuildTopo(c.In(0), t, c, "Vertex of Corner")) return;
      const int k = c.Int(1, 0);
      if (k < 0 || k >= t.corners) { c.Warn("Corner Index is outside the mesh"); c.Out(0, Value::Integer(0)); return; }
      size_t f = 0;
      while (f + 1 < t.rings.size() && t.offset[f + 1] <= k) ++f;
      c.Out(0, Value::Integer(t.rings[f][static_cast<size_t>(k - t.offset[f])]));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Corners of Vertex"; d.nick = "CornVert"; d.category = kCat; d.subcategory = "Mesh Topology";
    d.description = "The corners that sit on a vertex, in increasing corner number, and how many there are (one per face around the vertex). Corners are numbered as in Corners of Face.";
    d.inputs = {In("Mesh", Kind::Mesh), In("Vertex Index", Kind::Integer, Access::Item, Value::Integer(0))};
    d.outputs = {Out("Corner Index", Kind::Integer), Out("Total", Kind::Integer)};
    d.eval = [](EvalContext& c) {
      Topo t;
      if (!BuildTopo(c.In(0), t, c, "Corners of Vertex")) return;
      const int v = c.Int(1, 0);
      std::vector<int> out;
      for (size_t f = 0; f < t.rings.size(); ++f) for (size_t i = 0; i < t.rings[f].size(); ++i) if (t.rings[f][i] == v) out.push_back(t.offset[f] + static_cast<int>(i));
      c.OutList(0, IntList(out));
      c.Out(1, Value::Integer(static_cast<long long>(out.size())));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Edges of Vertex"; d.nick = "EdgeVert"; d.category = kCat; d.subcategory = "Mesh Topology";
    d.description = "The edges that meet at a vertex and how many there are. An edge is a distinct pair of vertices of a face (an n-gon contributes its boundary edges) or an edge with no face; edges are numbered by their place in the sorted list of such pairs, which is this program's own numbering.";
    d.inputs = {In("Mesh", Kind::Mesh), In("Vertex Index", Kind::Integer, Access::Item, Value::Integer(0))};
    d.outputs = {Out("Edge Index", Kind::Integer), Out("Total", Kind::Integer)};
    d.eval = [](EvalContext& c) {
      Topo t;
      if (!BuildTopo(c.In(0), t, c, "Edges of Vertex")) return;
      const int v = c.Int(1, 0);
      std::vector<int> out;
      for (size_t e = 0; e < t.edges.size(); ++e) if (t.edges[e].first == v || t.edges[e].second == v) out.push_back(static_cast<int>(e));
      c.OutList(0, IntList(out));
      c.Out(1, Value::Integer(static_cast<long long>(out.size())));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Vertex Neighbors"; d.nick = "VertNbr"; d.category = kCat; d.subcategory = "Mesh Topology";
    d.description = "For one vertex: Vertex Count, the number of edges that meet there (equally the number of distinct neighbouring vertices) and Face Count, the number of faces around it (an n-gon counts once).";
    d.inputs = {In("Mesh", Kind::Mesh), In("Vertex Index", Kind::Integer, Access::Item, Value::Integer(0))};
    d.outputs = {Out("Vertex Count", Kind::Integer), Out("Face Count", Kind::Integer)};
    d.eval = [](EvalContext& c) {
      Topo t;
      if (!BuildTopo(c.In(0), t, c, "Vertex Neighbors")) return;
      const int v = c.Int(1, 0);
      long long edges = 0, faces = 0;
      for (const auto& e : t.edges) if (e.first == v || e.second == v) ++edges;
      for (const auto& r2 : t.rings) if (std::find(r2.begin(), r2.end(), v) != r2.end()) ++faces;
      c.Out(0, Value::Integer(edges));
      c.Out(1, Value::Integer(faces));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Face Area"; d.nick = "FaceArea"; d.category = kCat; d.subcategory = "Mesh Topology";
    d.description = "The area of one face: half the length of the area vector of its boundary polygon (exact for a planar face; an n-gon is one face). Faces are numbered in face order. An index outside the mesh gives 0 with a warning.";
    d.inputs = {In("Mesh", Kind::Mesh), In("Face Index", Kind::Integer, Access::Item, Value::Integer(0))};
    d.outputs = {Out("Area", Kind::Number)};
    d.eval = [](EvalContext& c) {
      Topo t;
      if (!BuildTopo(c.In(0), t, c, "Face Area")) return;
      const int f = c.Int(1, 0);
      if (f < 0 || f >= static_cast<int>(t.rings.size())) { c.Warn("Face Index is outside the mesh"); c.Out(0, Value::Number(0)); return; }
      c.Out(0, Value::Number(RingNormal(t.d, t.rings[static_cast<size_t>(f)]).Length() / 2.0));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Mesh Island"; d.nick = "Island"; d.category = kCat; d.subcategory = "Mesh Topology";
    d.description = "Which connected piece a vertex belongs to, and how many pieces the mesh has. Two vertices are connected when a chain of faces or edges joins them; a vertex with nothing attached is a piece of its own. Island Index counts pieces in the order of their lowest vertex number, starting at 0.";
    d.inputs = {In("Mesh", Kind::Mesh), In("Vertex Index", Kind::Integer, Access::Item, Value::Integer(0))};
    d.outputs = {Out("Island Index", Kind::Integer), Out("Island Count", Kind::Integer)};
    d.eval = [](EvalContext& c) {
      Topo t;
      if (!BuildTopo(c.In(0), t, c, "Mesh Island")) return;
      const int n = static_cast<int>(t.d.v.size());
      std::vector<int> par(static_cast<size_t>(n));
      for (int i = 0; i < n; ++i) par[static_cast<size_t>(i)] = i;
      std::function<int(int)> find = [&](int x) { while (par[static_cast<size_t>(x)] != x) { par[static_cast<size_t>(x)] = par[static_cast<size_t>(par[static_cast<size_t>(x)])]; x = par[static_cast<size_t>(x)]; } return x; };
      for (const auto& e : t.edges) par[static_cast<size_t>(find(e.first))] = find(e.second);
      std::map<int, int> id;
      for (int i = 0; i < n; ++i) { const int root = find(i); if (!id.count(root)) { const int k = static_cast<int>(id.size()); id[root] = k; } }
      const int v = c.Int(1, 0);
      if (v < 0 || v >= n) { c.Warn("Vertex Index is outside the mesh"); c.Out(0, Value::Integer(0)); }
      else c.Out(0, Value::Integer(id[find(v)]));
      c.Out(1, Value::Integer(static_cast<long long>(id.size())));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Shortest Edge Paths"; d.nick = "EdgePath"; d.category = kCat; d.subcategory = "Mesh Topology";
    d.description = "Shortest path along the mesh's edges from a vertex to the End Vertex when every edge costs Edge Cost: Total Cost is the sum along the cheapest path and Next Vertex Index the neighbour that path goes to first (the lowest index among equally good neighbours; the End Vertex itself has cost 0 and is its own next vertex). A vertex the End Vertex cannot reach gets -1 and cost 0.";
    d.inputs = {In("Mesh", Kind::Mesh), In("End Vertex Index", Kind::Integer, Access::Item, Value::Integer(0)), In("Edge Cost", Kind::Number, Access::Item, Value::Number(1)),
                In("Vertex Index", Kind::Integer, Access::Item, Value::Integer(0))};
    d.outputs = {Out("Next Vertex Index", Kind::Integer), Out("Total Cost", Kind::Number)};
    d.eval = [](EvalContext& c) {
      Topo t;
      if (!BuildTopo(c.In(0), t, c, "Shortest Edge Paths")) return;
      const int n = static_cast<int>(t.d.v.size()), end = c.Int(1, 0), v = c.Int(3, 0);
      const double cost = c.Num(2, 1);
      if (!(cost >= 0) || end < 0 || end >= n || v < 0 || v >= n) { c.Fail("Edge Cost must not be negative and the indices must lie inside the mesh"); return; }
      std::vector<std::vector<int>> adj(static_cast<size_t>(n));
      for (const auto& e : t.edges) { adj[static_cast<size_t>(e.first)].push_back(e.second); adj[static_cast<size_t>(e.second)].push_back(e.first); }
      std::vector<double> dist(static_cast<size_t>(n), 1e300);
      std::priority_queue<std::pair<double, int>, std::vector<std::pair<double, int>>, std::greater<>> pq;
      dist[static_cast<size_t>(end)] = 0; pq.push({0.0, end});
      while (!pq.empty()) {
        const auto [dd, u] = pq.top(); pq.pop();
        if (dd > dist[static_cast<size_t>(u)]) continue;
        for (int w : adj[static_cast<size_t>(u)]) if (dd + cost < dist[static_cast<size_t>(w)]) { dist[static_cast<size_t>(w)] = dd + cost; pq.push({dd + cost, w}); }
      }
      if (v == end) { c.Out(0, Value::Integer(end)); c.Out(1, Value::Number(0)); return; }
      if (dist[static_cast<size_t>(v)] >= 1e299) { c.Out(0, Value::Integer(-1)); c.Out(1, Value::Number(0)); return; }
      int next = -1;
      for (int w : adj[static_cast<size_t>(v)]) if (std::fabs(dist[static_cast<size_t>(w)] + cost - dist[static_cast<size_t>(v)]) < 1e-9 * (1 + dist[static_cast<size_t>(v)]) && (next < 0 || w < next)) next = w;
      c.Out(0, Value::Integer(next));
      c.Out(1, Value::Number(dist[static_cast<size_t>(v)]));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Normal"; d.nick = "Normal"; d.category = kCat; d.subcategory = "Mesh Topology";
    d.description = "The unit normal at one element of a mesh. Domain 1 (Face): the normal of the face by its winding (counter-clockwise seen from the front, Newell's method). Domain 0 (Point): the normalised sum of the normals of the faces around the vertex, each weighted by its corner angle at the vertex. A vertex with no faces gets (0,0,0).";
    d.inputs = {In("Mesh", Kind::Mesh), In("Domain", Kind::Integer, Access::Item, Value::Integer(1)), In("Index", Kind::Integer, Access::Item, Value::Integer(0))};
    d.outputs = {Out("Normal", Kind::Vector)};
    d.eval = [](EvalContext& c) {
      Topo t;
      if (!BuildTopo(c.In(0), t, c, "Normal")) return;
      const int idx = c.Int(2, 0);
      Vector3d sum(0, 0, 0);
      if (c.Int(1, 1) == 1) {
        if (idx < 0 || idx >= static_cast<int>(t.rings.size())) { c.Warn("Index is outside the mesh"); c.Out(0, Value::Vector(sum)); return; }
        sum = RingNormal(t.d, t.rings[static_cast<size_t>(idx)]);
      } else {
        for (const auto& ring : t.rings) {
          for (size_t i = 0; i < ring.size(); ++i) {
            if (ring[i] != idx) continue;
            const Point3d& p = t.d.v[static_cast<size_t>(idx)];
            Vector3d a = t.d.v[static_cast<size_t>(ring[(i + ring.size() - 1) % ring.size()])] - p, b = t.d.v[static_cast<size_t>(ring[(i + 1) % ring.size()])] - p;
            if (!a.Unitize() || !b.Unitize()) continue;
            Vector3d n = RingNormal(t.d, ring);
            if (!n.Unitize()) continue;
            const double ang = std::acos(std::clamp(a.x * b.x + a.y * b.y + a.z * b.z, -1.0, 1.0));
            sum += n * ang;
          }
        }
      }
      sum.Unitize();
      c.Out(0, Value::Vector(sum));
    };
    r.Add(d);
  }
}

