# RW2DM_ALIGN: Align: objects by bounding boxes and control points to one another. The scripts are rw2dm_align_left_script.txt, rw2dm_align_right_script.txt, rw2dm_align_top_script.txt, rw2dm_align_bottom_script.txt, rw2dm_align_concentric_script.txt, rw2dm_align_horiz_script.txt, rw2dm_align_cp_left_script.txt, rw2dm_align_cp_region_script.txt, rw2dm_align_cp_one_script.txt, rw2dm_align_cp_conc_script.txt; generated by rw2dm_gen.py (the closed forms are in that file). Every object kind of the case (Point, Line, Plane, Box) is
# compared with the closed-form image of the operation: points by the residual move to the origin (printed 0,0,0 within 1e-9), curve / surface control points
# through ExtractPt the same way, boxes by their bounding box after a residual move. RW2DM_ALIGN_sensitivity shows that a 1e-6 error would read 1e-06.
RW2_ALIGN_OUT=""
rw2_align_run() {
  local o
  if [ -n "${DISPLAY:-}" ] && xset q >/dev/null 2>&1 || ! command -v xvfb-run >/dev/null 2>&1; then
    o="$(timeout 900 "$BIN" --smoke 60 --script "$HERE/$1" 2>&1)" || { echo "$o" | tail -40; echo "FAIL RW2DM_ALIGN_run: $1 exited non-zero"; fail=1; o=""; }
  else
    o="$(timeout 900 xvfb-run -a -s "-screen 0 1600x900x24" "$BIN" --smoke 60 --script "$HERE/$1" 2>&1)" || { echo "$o" | tail -40; echo "FAIL RW2DM_ALIGN_run: $1 exited non-zero"; fail=1; o=""; }
  fi
  RW2_ALIGN_OUT+="$o"$'\n'
}
