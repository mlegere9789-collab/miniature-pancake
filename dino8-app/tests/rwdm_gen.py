#!/usr/bin/env python3
"""Generates the RWDM_ app test sections (sections/94_rwdm_*.sh) and their scripts (rwdm_*_script.txt).

Oracle (independent of the app): every case places a few Point objects at integer coordinates, applies ONE transform command, and the
expected image of each point is computed HERE from the textbook closed form (Rodrigues rotation, reflection, scaling about an origin
along an axis, frame-to-frame map, shear / taper / twist / stretch definitions). The script then moves object k from its expected
position E_k to the origin (`Move E_k 0,0,0`, E_k typed with 17 significant digits) and lists the points: the app prints a coordinate
within 1e-9 of an integer as that integer ("0"), anything else with 4 significant digits (so a residual of 1e-6 reads "1e-06"). A
passing case therefore proves every point lies within 1e-9 (absolute, models here are about 10 units: 1e-10 relative) of the closed form.
Run:  python3 rwdm_gen.py   (rewrites the files next to it; the generated files are the ones committed)
"""
import math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SECT = os.path.join(HERE, "sections")

def add(a, b): return tuple(x + y for x, y in zip(a, b))
def sub(a, b): return tuple(x - y for x, y in zip(a, b))
def mul(a, s): return tuple(x * s for x in a)
def dot(a, b): return sum(x * y for x, y in zip(a, b))
def cross(a, b): return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])
def norm(a): return math.sqrt(dot(a, a))
def unit(a): n = norm(a); return mul(a, 1.0 / n)

def rodrigues(p, c, axis, deg):
    k = unit(axis); t = math.radians(deg); v = sub(p, c)
    r = add(add(mul(v, math.cos(t)), mul(cross(k, v), math.sin(t))), mul(k, dot(k, v) * (1 - math.cos(t))))
    return add(c, r)

def fmt(p): return ",".join(repr(float(x)) if x != int(x) else str(int(x)) for x in p)

class Case:
    def __init__(self, name, fixture, cmds, expected, view="Top"):
        self.name, self.fixture, self.cmds, self.expected, self.view = name, fixture, cmds, expected, view

FIX = [(1, 2, 0), (4, 2, 0), (1, 6, 3), (-3, 5, 2)]

def typed(view, p):
    """Typed coordinates are read in the active construction plane: Front's x axis is world X, its y axis world Z, its normal world -Y."""
    return (p[0], p[2], -p[1]) if view == "Front" else p

def case_text(cs):
    out = ["New"]
    out.append("SetActiveViewport " + cs.view)
    out.append("RWDMBEGIN_" + cs.name)
    for p in cs.fixture: out.append("Point " + fmt(typed(cs.view, p)))
    out.append("SelAll")
    out += cs.cmds
    for k, e in enumerate(cs.expected, 1):
        out += ["SelNone", "SelID %d" % k, "Move %s 0,0,0" % fmt(typed(cs.view, e))]
    out += ["SelAll", "List"]
    return out

SHEAD = r"""# RWDM_@UP@: @TITLE@. The script @SCRIPT@ is generated by rwdm_gen.py (the closed forms are in that file); every case moves each Point object
# from its closed-form image E_k to the origin and lists it: the app prints a coordinate within 1e-9 of an integer as that integer, so a
# passing case means every image lies within 1e-9 of the textbook formula (a residual of 1e-6 would read 1e-06; RWDM_*_sensitivity checks that).
if [ -n "${DISPLAY:-}" ] && xset q >/dev/null 2>&1 || ! command -v xvfb-run >/dev/null 2>&1; then
  RWDM_@UP@_OUT="$(timeout 900 "$BIN" --smoke 60 --script "$HERE/@SCRIPT@" 2>&1)" || { echo "$RWDM_@UP@_OUT" | tail -40; echo "FAIL RWDM_@UP@_run: script exited non-zero"; fail=1; RWDM_@UP@_OUT=""; }
else
  RWDM_@UP@_OUT="$(timeout 900 xvfb-run -a -s "-screen 0 1600x900x24" "$BIN" --smoke 60 --script "$HERE/@SCRIPT@" 2>&1)" || { echo "$RWDM_@UP@_OUT" | tail -40; echo "FAIL RWDM_@UP@_run: script exited non-zero"; fail=1; RWDM_@UP@_OUT=""; }
fi
rwdm_@LO@_block() { awk -v name="$1" '$0 ~ ("Unknown command: RWDMBEGIN_" name "$") { on = 1; next } on && /Unknown command: RWDMBEGIN_/ { exit } on { print }' <<<"$RWDM_@UP@_OUT"; }
# rwdm_@LO@_check NAME N DESC: the case listed exactly N points and every one of them is "0,0,0" (the residual to the closed form)
rwdm_@LO@_check() {
  local blk npts zeros; blk="$(rwdm_@LO@_block "$1")"
  npts="$({ grep -cE '^history: Object [0-9]+ \(point\)' <<<"$blk" || true; })"
  zeros="$({ grep -cE '^history:   0,0,0$' <<<"$blk" || true; })"
  if [ "$npts" = "$2" ] && [ "$zeros" = "$2" ]; then echo "ok   RWDM_@UP@_$1: $3 ($2 points, every one within 1e-9 of the closed form)"
  else echo "FAIL RWDM_@UP@_$1: $3 (listed $npts points, $zeros at residual 0; expected $2 and $2)"; fail=1; { grep -E '^history:   ' <<<"$blk" || true; } | head -12 | sed 's/^/     residual: /'; fi
}
"""

SENS = r"""# negative control: the same harness must SEE a 1e-6 error (point moved 1e-6 off its expected image reads 1e-06, not 0)
rwdm_@LO@_sens() {
  local blk; blk="$(rwdm_@LO@_block sensitivity)"
  if grep -qE '^history:   (0,0,)?[-0-9.e]*1e-06' <<<"$blk" && ! grep -qE '^history:   0,0,0$' <<<"$blk"; then echo "ok   RWDM_@UP@_sensitivity: the residual harness reports a 1e-6 error as 1e-06 (negative control)"
  else echo "FAIL RWDM_@UP@_sensitivity: a 1e-6 error was not visible"; fail=1; { grep -E '^history:   ' <<<"$blk" || true; } | head -4 | sed 's/^/     residual: /'; fi
}
rwdm_@LO@_sens
"""

def sens_case():
    # a point 1e-6 away from where the residual move expects it
    return ["New", "SetActiveViewport Top", "RWDMBEGIN_sensitivity", "Point 1,2,3.000001", "SelAll", "Move 1,2,3 0,0,0", "SelAll", "List"]

def build(section, title, rows, cases, view_default="Top"):
    lo = section; up = section.upper()
    script = "rwdm_%s_script.txt" % lo
    lines = ["# RWDM_%s: %s. Generated by rwdm_gen.py; rows %s." % (up, title, ", ".join(rows)), "# Oracle: closed forms computed in rwdm_gen.py; residual = Move of each point from its expected image to the origin, listed (see sections/94_rwdm_%s.sh)." % lo, "SetActiveViewport Top"]
    for cs in cases: lines += case_text(cs)
    lines += sens_case()
    lines += ["Check"]
    open(os.path.join(HERE, script), "w").write("\n".join(lines) + "\n")
    sh = SHEAD.replace("@UP@",up).replace("@LO@",lo).replace("@TITLE@",title).replace("@SCRIPT@",script)
    for cs in cases:
        sh += 'rwdm_%s_check %s %d "%s"\n' % (lo, cs.name, len(cs.expected), cs.desc if hasattr(cs, "desc") else cs.name)
    sh += SENS.replace("@UP@",up).replace("@LO@",lo)
    open(os.path.join(SECT, "94_rwdm_%s.sh" % lo), "w").write(sh)

def C(name, desc, fixture, cmds, expected, view="Top"):
    c = Case(name, fixture, cmds, expected, view); c.desc = desc; return c

def softmove():
    """SoftMove: shape-independent invariants of a falloff move (the row does not fix the falloff curve): the picked point moves by the full
    vector, a point at or beyond the radius does not move, and a point in between moves by a strictly smaller, strictly decreasing
    fraction of the vector in the same direction. Closed forms: from (0,0,0) to (0,4,0), radius 10."""
    lines = ["# RWDM_SOFTMOVE: SoftMove invariants. Generated by rwdm_gen.py; row D8-RHINO-XFORM-0043.", "SetActiveViewport Top", "New", "SetActiveViewport Top", "RWDMBEGIN_falloff"]
    pts = [(0, 0, 0), (2.5, 0, 0), (5, 0, 0), (7.5, 0, 0), (10, 0, 0), (12, 3, 0)]
    for p in pts: lines.append("Point " + fmt(p))
    lines += ["SelAll", "SoftMove 0,0,0 0,4,0 Radius=10"]
    # exact ones by residual: id1 moved by the full (0,4,0); id5 (d = radius) and id6 (outside) unmoved
    for k, e in ((1, (0, 4, 0)), (5, (10, 0, 0)), (6, (12, 3, 0))): lines += ["SelNone", "SelID %d" % k, "Move %s 0,0,0" % fmt(e)]
    lines += ["SelNone", "SelID 2 3 4", "List"]
    lines += ["SelAll", "List"]
    lines += sens_case() + ["Check"]
    open(os.path.join(HERE, "rwdm_softmove_script.txt"), "w").write("\n".join(lines) + "\n")
    sh = SHEAD.replace("@UP@", "SOFTMOVE").replace("@LO@", "softmove").replace("@TITLE@", "SoftMove: move relative to a centre with a falloff distance").replace("@SCRIPT@", "rwdm_softmove_script.txt")
    sh += r"""# the last List (all 6 points) carries the residuals of ids 1, 5, 6 (must be 0,0,0) and the raw positions of ids 2..4 (moved up by a fraction of 4)
RWDM_SOFTMOVE_BLK="$(rwdm_softmove_block falloff)"
RWDM_SOFTMOVE_Y="$({ grep -E '^history:   [-0-9.e+]+,[-0-9.e+]+,[-0-9.e+]+$' <<<"$RWDM_SOFTMOVE_BLK" || true; } | tail -6)"
rwdm_softmove_pt() { sed -n "$1p" <<<"$RWDM_SOFTMOVE_Y" | sed 's/^history:   //'; }
if [ "$(rwdm_softmove_pt 1)" = "0,0,0" ] && [ "$(rwdm_softmove_pt 5)" = "0,0,0" ] && [ "$(rwdm_softmove_pt 6)" = "0,0,0" ]; then echo "ok   RWDM_SOFTMOVE_exact: the picked point moved by the full vector (0,4,0) and the points at distance 10 and 13 (>= radius) did not move (residual 0,0,0 within 1e-9)"
else echo "FAIL RWDM_SOFTMOVE_exact: residuals of the picked, the at-radius and the outside point were '$(rwdm_softmove_pt 1)' '$(rwdm_softmove_pt 5)' '$(rwdm_softmove_pt 6)' (expected 0,0,0 each)"; fail=1; fi
# ids 2..4 are the 2nd..4th rows of the last listing; their y is the moved fraction * 4, their x the original 2.5, 5, 7.5
RWDM_SOFTMOVE_OK=1; RWDM_SOFTMOVE_PREV=4
for i in 2 3 4; do
  p="$(rwdm_softmove_pt $i)"; x="${p%%,*}"; y="${p#*,}"; y="${y%%,*}"; ex="$(awk -v k="$i" 'BEGIN { printf "%g", 2.5 * (k - 1) }')"
  if ! awk -v x="$x" -v ex="$ex" -v y="$y" -v prev="$RWDM_SOFTMOVE_PREV" 'BEGIN { d = x - ex; if (d < 0) d = -d; exit !(d < 1e-9 && y > 0 && y < prev) }'; then RWDM_SOFTMOVE_OK=0; echo "     point $i: x=$x (expected $ex) y=$y (expected 0 < y < $RWDM_SOFTMOVE_PREV)"; fi
  RWDM_SOFTMOVE_PREV="$y"
done
if [ "$RWDM_SOFTMOVE_OK" = 1 ]; then echo "ok   RWDM_SOFTMOVE_falloff: inside the radius each point moves along the vector by a fraction strictly between 0 and 1 that strictly decreases with the distance from the picked point (x untouched)"
else echo "FAIL RWDM_SOFTMOVE_falloff: the falloff is not strictly between 0 and the full move and strictly decreasing"; fail=1; fi
"""
    sh += SENS.replace("@UP@", "SOFTMOVE").replace("@LO@", "softmove")
    open(os.path.join(SECT, "94_rwdm_softmove.sh"), "w").write(sh)

