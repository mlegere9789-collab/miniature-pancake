def build_logic(section, title, rows, setup, steps, defs_sh="", calls_sh="", base=None, tmp=False):
    """steps: dict(name, desc, cmds, show: 'sel'|'all', expect: [(id, kind, layer, name)], pats: [regex])"""
    lo = section; up = section.upper(); script = "rw4dm_%s_script.txt" % lo
    lines = ["# RW4DM_%s: %s. Generated by rw4dm_gen.py; rows %s." % (up, title, ", ".join(rows)), "SetActiveViewport Top", "New", "SetActiveViewport Top"]
    lines += setup
    kinds = ["pt", "line", "plane", "box"]
    base = base if base is not None else [Pt(1, 0, 0), Ln((2, 0, 0), (2, 3, 0)), Pl(3, 0, 4, 1), Bx(5, 0, 6, 1, 0, 1)]
    lines += [create_cmd(o) if hasattr(o, "kind") else o for o in base]
    head = LHEAD
    if tmp:
        head = head.replace('RW4_@UP@_OUT=""\n', 'RW4_@UP@_OUT=""\nsed "s|@TMP@|$TMPW|g" "$HERE/@SCRIPT@" > "$TMPW/@SCRIPT@"\n', 1).replace('--script "$HERE/@SCRIPT@"', '--script "$TMPW/@SCRIPT@"')
    sh = head.replace("@UP@", up).replace("@LO@", lo).replace("@TITLE@", title).replace("@SCRIPT@", script)
    sh += defs_sh.replace("@UP@", up).replace("@LO@", lo)
    for st in steps:
        lines.append("RW4BEGIN_" + st["name"])
        lines += st["cmds"]
        show = st.get("show", "all")
        if show == "all": lines += ["SelNone", "SelAll"]
        if show != "none":
            lines.append("List")
            if not st["expect"]: lines.append("Cancel")
        exp = " ".join("%d:%s:%s%s" % (i, k, l, (":" + n) if n else "") for (i, k, l, n) in st["expect"]) or "-"
        pats = " ".join('"%s"' % p.replace('"', '\\"') for p in st.get("pats", []))
        if st.get("check", True): sh += 'rw4_%s_state %s "%s" "%s" %s\n' % (lo, st["name"], exp, st["desc"].replace('"', "'"), pats)
    sh += calls_sh.replace("@UP@", up).replace("@LO@", lo)
    lines += ["Check"]
    open(os.path.join(HERE, script), "w").write("\n".join(lines) + "\n")
    open(os.path.join(SECT, "96_rw4dm_%s.sh" % lo), "w").write(sh)

