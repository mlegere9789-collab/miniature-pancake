    d.description = "Sweeps a profile along the poly spline. Each point of the curve gets a copy of the profile points placed in the plane across the curve's tangent T (profile X along cross(Z, T) normalised, profile Y along T x X; the identity when T is +Z; X is world X when T is parallel to Z). T at a point is the normalised difference of its neighbours. One quad joins neighbouring copies of neighbouring profile points: V = n m, F = (n - 1 or n if cyclic) * (m - 1 or m if the profile is cyclic). Fill Caps adds an n-gon at each end of an open curve with a cyclic profile. Without a profile the result is the curve's points joined by edges.";
    d.inputs = {In("Curve", Kind::Curve), In("Profile Curve", Kind::Curve, Access::Item, Value::Null(), true), In("Fill Caps", Kind::Boolean, Access::Item, Value::Boolean(false))};
    d.outputs = {Out("Mesh", Kind::Mesh)};
