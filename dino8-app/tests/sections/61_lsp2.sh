# ---------------------------------------------------------------------------
# LSP2_: AutoLISP-style Lisp dialect, second pass (src/script/Lisp.cpp, commands/cmd_lisp.cpp). PARITY_MAP.md
# "AutoLISP-equivalent command scripting language": dotted pairs, entity access (entget / entmod / entdel / entnext,
# ssget filter lists, ssadd / ssdel), typed input (getint / getreal / getpoint / getstring / getkword / initget) and
# the vl-* subset. One real app process runs lisp2_script.txt; every expected value is computed here with bash / awk
# or is the documented semantics of the function. Self-contained (it defines its own helpers) so that
# `run_sections.sh LSP2` works alone.
# ---------------------------------------------------------------------------
lsp2_exec() {  # lsp2_exec <config home> <script>
  if [ -n "${DISPLAY:-}" ] && xset q >/dev/null 2>&1 || ! command -v xvfb-run >/dev/null 2>&1; then
    XDG_CONFIG_HOME="$1" APPDATA="$1" timeout 900 "$BIN" --smoke 100 --script "$2" 2>&1
  else
    XDG_CONFIG_HOME="$1" APPDATA="$1" timeout 900 xvfb-run -a -s "-screen 0 1600x900x24" "$BIN" --smoke 100 --script "$2" 2>&1
  fi
}
lsp2_ok() { echo "ok   $1"; }
lsp2_bad() { echo "FAIL $1"; fail=1; }
# the lines a command printed: after its exact "Command: <text>" echo (the Nth one) up to the next "Command:" line
lsp2_blk() { sed "s/^history: //" <<<"$1" | awk -v n="$3" -v cmd="Command: $2" '$0==cmd{c++; on=(c==n); next} /^Command:/{on=0} on'; }
# <output> <typed text> <nth> <expected text after "Lisp: "> <description>
lsp2_is() {
  local blk got
  blk="$(lsp2_blk "$1" "$2" "$3")"
  got="$(grep -m1 '^Lisp: ' <<<"$blk" || true)"; got="${got#Lisp: }"
  if [ -n "$got" ] && [ "$got" = "$4" ]; then lsp2_ok "$5 ($2 -> $got)"; else lsp2_bad "$5: '$2' (#$3) gave '$got', expected '$4'"; near "$blk" "$4"; fi
}
# <output> <typed text> <nth> <substring that block must contain> <description>
lsp2_has() {
  local blk; blk="$(lsp2_blk "$1" "$2" "$3")"
  if grep -qF -- "$4" <<<"$blk"; then lsp2_ok "$5"; else lsp2_bad "$5: '$2' (#$3) printed no '$4'"; echo "$blk" | head -6 | sed 's/^/     actual:   /'; fi
}
# the block prints "Lisp error" (the program was stopped) and contains the substring
lsp2_err() {  # <output> <typed text> <nth> <substring of the error> <description>
  local blk; blk="$(lsp2_blk "$1" "$2" "$3")"
  if grep -qF -- "$4" <<<"$blk" && grep -q 'error' <<<"$blk" && ! grep -q '^Lisp: ' <<<"$blk"; then lsp2_ok "$5"; else lsp2_bad "$5: '$2' (#$3) did not stop with '$4'"; echo "$blk" | head -6 | sed 's/^/     actual:   /'; fi
}
# a real number the way the app prints it: six decimals, trailing zeros trimmed down to one
lsp2_r() {
  local s; s="$(awk -v x="$1" 'BEGIN { printf "%.6f", x }')"
  while [[ "$s" == *0 && "${s%?}" != *. ]]; do s="${s%?}"; done
  [ "$s" = "-0.0" ] && s="0.0"
  echo "$s"
}
# "Total length = x" / "Volume = x" of the Nth such command, against an expected value (relative 1e-3: Length prints 4 significant digits)
lsp2_meas() {  # <output> <Length|Volume> <nth> <expected> <description>
  local blk got
  blk="$(lsp2_blk "$1" "$2" "$3")"
  got="$(grep -m1 -o "\(Total length\|$2\) = [-0-9.e+]*" <<<"$blk" || true)"; got="${got##* = }"
  if [ -n "$got" ] && awk -v a="$got" -v b="$4" 'BEGIN { d = a - b; if (d < 0) d = -d; exit !(d <= 1e-3 * b) }'; then lsp2_ok "$5 ($2 $got)"; else lsp2_bad "$5: $2 read '$got', expected $4"; near "$blk" "$2 = $4"; fi
}

