# RW2DM_SETPT: SetPt: move points and control points to a coordinate. The scripts are rw2dm_setpt_points_script.txt, rw2dm_setpt_cp_x_script.txt, rw2dm_setpt_cp_region_script.txt, rw2dm_setpt_cp_xyz_script.txt; generated by rw2dm_gen.py (the closed forms are in that file). Every object kind of the case (Point, Line, Plane, Box) is
# compared with the closed-form image of the operation: points by the residual move to the origin (printed 0,0,0 within 1e-9), curve / surface control points
# through ExtractPt the same way, boxes by their bounding box after a residual move. RW2DM_SETPT_sensitivity shows that a 1e-6 error would read 1e-06.
RW2_SETPT_OUT=""
rw2_setpt_run() {
  local o
  if [ -n "${DISPLAY:-}" ] && xset q >/dev/null 2>&1 || ! command -v xvfb-run >/dev/null 2>&1; then
    o="$(timeout 900 "$BIN" --smoke 60 --script "$HERE/$1" 2>&1)" || { echo "$o" | tail -40; echo "FAIL RW2DM_SETPT_run: $1 exited non-zero"; fail=1; o=""; }
  else
    o="$(timeout 900 xvfb-run -a -s "-screen 0 1600x900x24" "$BIN" --smoke 60 --script "$HERE/$1" 2>&1)" || { echo "$o" | tail -40; echo "FAIL RW2DM_SETPT_run: $1 exited non-zero"; fail=1; o=""; }
  fi
  RW2_SETPT_OUT+="$o"$'\n'
}
rw2_setpt_run rw2dm_setpt_points_script.txt
rw2_setpt_run rw2dm_setpt_cp_x_script.txt
rw2_setpt_run rw2dm_setpt_cp_region_script.txt
rw2_setpt_run rw2dm_setpt_cp_xyz_script.txt
rw2_setpt_block() { awk -v name="$1" '$0 ~ ("Unknown command: RW2BEGIN_" name "$") { on = 1; next } on && /Unknown command: RW2BEGIN_/ { exit } on { print }' <<<"$RW2_SETPT_OUT"; }
# rw2_setpt_resid NAME NPTS BOXES DESC: the case listed exactly NPTS points, every one at residual 0,0,0, and the boxes' bounding boxes (joined by ';') read exactly BOXES
rw2_setpt_resid() {
  local blk npts zeros boxes; blk="$(rw2_setpt_block "$1")"
  npts="$({ grep -cE '^history: Object [0-9]+ \(point\)' <<<"$blk" || true; })"
  zeros="$({ grep -cE '^history:   0,0,0$' <<<"$blk" || true; })"
  boxes="$({ grep -E '^history: Bounding box min ' <<<"$blk" || true; } | sed -E 's/^history: Bounding box //' | paste -sd';' -)"
  if [ "$npts" = "$2" ] && [ "$zeros" = "$2" ] && [ "$boxes" = "$3" ]; then echo "ok   RW2DM_SETPT_$1: $4 ($2 points at residual 0 within 1e-9; boxes: ${3:-none})"
  else echo "FAIL RW2DM_SETPT_$1: $4 (listed $npts points, $zeros at residual 0, expected $2 and $2; boxes '$boxes', expected '$3')"; fail=1; { grep -E '^history:   |^history: Bounding box|^history: ! ' <<<"$blk" || true; } | head -16 | sed 's/^/     residual: /'; fi
}
rw2_setpt_resid points 3 "" "SetPt SetX=Yes SetY=Yes X=3 Y=4 Z=5 moves every selected Point object to (3,4,5)"
rw2_setpt_resid cp_x 6 "" "SetPt SetX=Yes X=2 SetZ=No on all 6 control points of a line and a plane (SelControlPoint): every control point's x = 2, y and z kept"
rw2_setpt_resid cp_region 7 "" "SetPt Z=7 on the three control points chosen by SelControlPointRegion (x in 0..3) of a line and a plane, and on a Point object: only those control points get z = 7, the others stay"
rw2_setpt_resid cp_xyz 2 "" "SetPt SetX=Yes SetY=Yes X=-1 Y=-2 Z=3 on all control points of a line: both control points land on (-1,-2,3) (the line collapses to a point)"
# negative control: the same harness must SEE a 1e-6 error (a point 1e-6 off its expected image reads 1e-06, not 0)
rw2_setpt_sens() {
  local blk; blk="$(rw2_setpt_block sensitivity)"
  if grep -qE '^history:   (0,0,)?[-0-9.e]*1e-06' <<<"$blk" && ! grep -qE '^history:   0,0,0$' <<<"$blk"; then echo "ok   RW2DM_SETPT_sensitivity: the residual harness reports a 1e-6 error as 1e-06 (negative control)"
  else echo "FAIL RW2DM_SETPT_sensitivity: a 1e-6 error was not visible"; fail=1; { grep -E '^history:   ' <<<"$blk" || true; } | head -4 | sed 's/^/     residual: /'; fi
}
rw2_setpt_sens
