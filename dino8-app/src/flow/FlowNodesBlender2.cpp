// Resampled positions along a poly line: n points, open: spacing L/(n-1), cyclic: L/n. Also the unit tangent of the edge
// each point lies on (the outgoing edge at a vertex).
void WalkPoly(const Poly& p, const std::vector<double>& s_list, std::vector<Point3d>& pos, std::vector<Vector3d>& tan) {
  std::vector<Point3d> ring = p.pts;
  if (p.closed) ring.push_back(p.pts.front());
  std::vector<double> cum(ring.size(), 0.0);
  for (size_t i = 1; i < ring.size(); ++i) cum[i] = cum[i - 1] + ring[i - 1].DistanceTo(ring[i]);
  const double total = cum.back();
  for (double s0 : s_list) {
    const double s = std::clamp(s0, 0.0, total);
    size_t seg = 0;
    while (seg + 2 < ring.size() && cum[seg + 1] <= s) ++seg;
    const double len = cum[seg + 1] - cum[seg];
    const double t = len > 0 ? std::clamp((s - cum[seg]) / len, 0.0, 1.0) : 0.0;
    pos.push_back(ring[seg] + (ring[seg + 1] - ring[seg]) * t);
    Vector3d d = ring[seg + 1] - ring[seg];
    d.Unitize();
    tan.push_back(d);
  }
}

// Ear clipping of a simple polygon given as 3D points on a plane; returns triangles as index triples in polygon order.
std::vector<std::array<int, 3>> EarClip(const std::vector<Point3d>& ring) {
  const int n = static_cast<int>(ring.size());
  Vector3d nrm(0, 0, 0);
  for (int i = 0; i < n; ++i) {
    const Point3d& a = ring[static_cast<size_t>(i)];
    const Point3d& b = ring[static_cast<size_t>((i + 1) % n)];
    nrm.x += (a.y - b.y) * (a.z + b.z); nrm.y += (a.z - b.z) * (a.x + b.x); nrm.z += (a.x - b.x) * (a.y + b.y);
  }
  if (!nrm.Unitize()) return {};
  Vector3d u = ON_CrossProduct(nrm, std::fabs(nrm.x) < 0.9 ? Vector3d(1, 0, 0) : Vector3d(0, 1, 0));
  u.Unitize();
  const Vector3d w = ON_CrossProduct(nrm, u);
  std::vector<std::array<double, 2>> q;
  for (const Point3d& p : ring) q.push_back({p.x * u.x + p.y * u.y + p.z * u.z, p.x * w.x + p.y * w.y + p.z * w.z});
  auto cross = [&](int a, int b, int c) {
    return (q[static_cast<size_t>(b)][0] - q[static_cast<size_t>(a)][0]) * (q[static_cast<size_t>(c)][1] - q[static_cast<size_t>(a)][1]) -
           (q[static_cast<size_t>(b)][1] - q[static_cast<size_t>(a)][1]) * (q[static_cast<size_t>(c)][0] - q[static_cast<size_t>(a)][0]);
  };
  std::vector<int> idx(static_cast<size_t>(n));
  for (int i = 0; i < n; ++i) idx[static_cast<size_t>(i)] = i;
  std::vector<std::array<int, 3>> tris;
  int guard = 0;
  while (idx.size() > 3 && guard++ < 100000) {
    bool clipped = false;
    const size_t m = idx.size();
    for (size_t i = 0; i < m; ++i) {
      const int a = idx[(i + m - 1) % m], b = idx[i], c = idx[(i + 1) % m];
      if (cross(a, b, c) <= 1e-14) continue;
      bool inside = false;
      for (size_t k = 0; k < m && !inside; ++k) {
        const int p = idx[k];
        if (p == a || p == b || p == c) continue;
        if (cross(a, b, p) >= 0 && cross(b, c, p) >= 0 && cross(c, a, p) >= 0) inside = true;
      }
      if (inside) continue;
      tris.push_back({a, b, c});
      idx.erase(idx.begin() + static_cast<long>(i));
      clipped = true;
      break;
    }
    if (!clipped) return {};
  }
  if (idx.size() == 3) tris.push_back({idx[0], idx[1], idx[2]});
  return tris;
}

void Mat(const Vector3d& rot, const Vector3d& scl, double m[3][3]) {
  const double cx = std::cos(rot.x), sx = std::sin(rot.x), cy = std::cos(rot.y), sy = std::sin(rot.y), cz = std::cos(rot.z), sz = std::sin(rot.z);
  // R = Rz * Ry * Rx (the X rotation is applied first), then the columns are scaled: M = R * S
  const double r[3][3] = {{cz * cy, cz * sy * sx - sz * cx, cz * sy * cx + sz * sx},
                          {sz * cy, sz * sy * sx + cz * cx, sz * sy * cx - cz * sx},
                          {-sy, cy * sx, cy * cx}};
  const double s[3] = {scl.x, scl.y, scl.z};
  for (int i = 0; i < 3; ++i) for (int j = 0; j < 3; ++j) m[i][j] = r[i][j] * s[j];
}

Point3d Apply(const double m[3][3], const Vector3d& t, const Point3d& p) {
  return Point3d(m[0][0] * p.x + m[0][1] * p.y + m[0][2] * p.z + t.x, m[1][0] * p.x + m[1][1] * p.y + m[1][2] * p.z + t.y,
                 m[2][0] * p.x + m[2][1] * p.y + m[2][2] * p.z + t.z);
}

std::vector<Point3d> VertexPoints(const Value& g) {
  std::vector<Point3d> pts;
  if (const kernel::Mesh* m = MeshOf(g)) { const ON_Mesh& r = m->raw(); for (int i = 0; i < r.VertexCount(); ++i) pts.push_back(Point3d(r.m_V[i].x, r.m_V[i].y, r.m_V[i].z)); }
  else { Poly p; if (CurvePoly(g, p)) pts = p.pts; else if (g.kind == Kind::Point) pts.push_back(g.point); }
  return pts;
}


