void AddMisc3() {
  Registry& r = Registry::Get();
  {
    NodeDef d; d.name = "Spline Length"; d.nick = "SplLen"; d.category = kCat; d.subcategory = "Curve";
    d.description = "Length: the total length of the poly spline, the closing edge of a cyclic one included. Point Count: how many points it has (a repeated closing point is not counted).";
    d.inputs = {In("Curve", Kind::Curve)};
    d.outputs = {Out("Length", Kind::Number), Out("Point Count", Kind::Integer)};
    d.eval = [](EvalContext& c) {
      Poly p;
      if (!CurvePoly(c.In(0), p)) { c.Fail("Spline Length needs a curve"); return; }
      c.Out(0, Value::Number(PolyLength(p)));
      c.Out(1, Value::Integer(static_cast<long long>(p.pts.size())));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Is Spline Cyclic"; d.nick = "IsCyclic"; d.category = kCat; d.subcategory = "Curve";
    d.description = "True when the poly spline is cyclic (its last point joins back to the first).";
    d.inputs = {In("Curve", Kind::Curve)};
    d.outputs = {Out("Cyclic", Kind::Boolean)};
    d.eval = [](EvalContext& c) {
      Poly p;
      if (!CurvePoly(c.In(0), p)) { c.Fail("Is Spline Cyclic needs a curve"); return; }
      c.Out(0, Value::Boolean(p.closed));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Spline Parameter"; d.nick = "SplParam"; d.category = kCat; d.subcategory = "Curve";
    d.description = "Where a point sits along its spline: Length, the distance along the spline from the first point to it; Factor, that distance as a fraction of the total length (the closing edge of a cyclic spline included); Index, the point's position in the spline. Point Index outside the spline gives 0, 0, 0 with a warning.";
    d.inputs = {In("Curve", Kind::Curve), In("Point Index", Kind::Integer, Access::Item, Value::Integer(0))};
    d.outputs = {Out("Factor", Kind::Number), Out("Length", Kind::Number), Out("Index", Kind::Integer)};
    d.eval = [](EvalContext& c) {
      Poly p;
      if (!CurvePoly(c.In(0), p)) { c.Fail("Spline Parameter needs a curve"); return; }
      const int k = c.Int(1, 0);
      if (k < 0 || k >= static_cast<int>(p.pts.size())) { c.Warn("Point Index is outside the spline"); c.Out(0, Value::Number(0)); c.Out(1, Value::Number(0)); c.Out(2, Value::Integer(0)); return; }
      double len = 0;
      for (int i = 0; i < k; ++i) len += p.pts[static_cast<size_t>(i)].DistanceTo(p.pts[static_cast<size_t>(i + 1)]);
      const double total = PolyLength(p);
      c.Out(0, Value::Number(total > 0 ? len / total : 0.0));
      c.Out(1, Value::Number(len));
      c.Out(2, Value::Integer(k));
    };
    r.Add(d);
  }
  auto import_node = [&r](const char* name, const char* nick, const char* what, kernel::Result (*load)(const std::string&, kernel::Mesh&), bool weld) {
    NodeDef d; d.name = name; d.nick = nick; d.category = kCat; d.subcategory = "Import";
    d.description = what;
    d.inputs = {In("Path", Kind::Text, Access::Item, Value::Text(""))};
    d.outputs = {Out("Mesh", Kind::Mesh)};
    d.eval = [load, weld, name](EvalContext& c) {
      const std::string path = c.Text(0);
      if (path.empty()) { c.Fail(std::string(name) + " needs a file path"); return; }
      kernel::Mesh m;
      try {
        if (load(path, m) != kernel::Result::Ok) { c.Fail(std::string(name) + " could not read " + path); return; }
        if (weld) m = kernel::Mesh::MergeAndWeld({m});
      } catch (const std::exception& ex) { c.Fail(ex.what()); return; }
      c.Out(0, Value::MeshV(m));
    };
    r.Add(d);
  };
  import_node("Import OBJ", "ImpOBJ", "Reads the mesh of a Wavefront .obj file at Path in the file's own coordinates (no axis conversion is applied): vertices as listed, 3- and 4-corner faces as they are, longer faces split into triangles. A file that cannot be read is flagged.", &kernel::Mesh::LoadObj, false);
  import_node("Import PLY", "ImpPLY", "Reads the mesh of a Stanford .ply file at Path (ascii or binary): vertices as listed, 3- and 4-corner faces as they are, longer faces split into triangles. A file that cannot be read is flagged.", &kernel::Mesh::LoadPly, false);
  import_node("Import STL", "ImpSTL", "Reads the triangles of an .stl file at Path (ascii or binary) and welds vertices that coincide, so a closed solid comes back with one vertex per corner of the solid. A file that cannot be read is flagged.", &kernel::Mesh::LoadStl, true);
  {
    NodeDef d; d.name = "Import Text"; d.nick = "ImpTxt"; d.category = kCat; d.subcategory = "Import";
    d.description = "Reads the whole file at Path as one string, byte for byte (at most 64 MB). A file that cannot be read is flagged.";
    d.inputs = {In("Path", Kind::Text, Access::Item, Value::Text(""))};
    d.outputs = {Out("String", Kind::Text)};
    d.eval = [](EvalContext& c) {
      const std::string path = c.Text(0);
      std::ifstream in(path, std::ios::binary);
      if (path.empty() || !in) { c.Fail("Import Text could not read " + path); return; }
      std::string s((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
      if (s.size() > (64u << 20)) { c.Fail("The file is larger than 64 MB"); return; }
      c.Out(0, Value::Text(s));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Attribute Statistic"; d.nick = "AttrStat"; d.category = kCat; d.subcategory = "Statistics";
    d.description = "Statistics of a list of numbers: Mean (sum / n), Median (the middle value of the sorted list, the upper of the two middle ones for an even count), Sum, Min, Max, Range (Max - Min), Standard Deviation and Variance (the mean of the squared distances from the mean, so over n and not n - 1). An empty list is flagged.";
    d.inputs = {In("Attribute", Kind::Number, Access::List)};
    d.outputs = {Out("Mean", Kind::Number), Out("Median", Kind::Number), Out("Sum", Kind::Number), Out("Min", Kind::Number), Out("Max", Kind::Number),
                 Out("Range", Kind::Number), Out("Standard Deviation", Kind::Number), Out("Variance", Kind::Number)};
    d.eval = [](EvalContext& c) {
      const std::vector<double> x = Numbers(c.List(0));
      if (x.empty()) { c.Fail("Attribute Statistic needs at least one number"); return; }
      const Stats s = Compute(x);
      const double out[8] = {s.mean, s.median, s.sum, s.mn, s.mx, s.range, s.sd, s.var};
      for (int i = 0; i < 8; ++i) c.Out(i, Value::Number(out[i]));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Field Average"; d.nick = "FldAvg"; d.category = kCat; d.subcategory = "Statistics";
    d.description = "Mean and Median of a list of numbers (one group; Group ID is not modelled). Median is the middle value of the sorted list, the upper of the two middle ones for an even count. An empty list is flagged.";
    d.inputs = {In("Value", Kind::Number, Access::List)};
    d.outputs = {Out("Mean", Kind::Number), Out("Median", Kind::Number)};
    d.eval = [](EvalContext& c) {
      const std::vector<double> x = Numbers(c.List(0));
      if (x.empty()) { c.Fail("Field Average needs at least one number"); return; }
      const Stats s = Compute(x);
      c.Out(0, Value::Number(s.mean)); c.Out(1, Value::Number(s.median));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Field Min & Max"; d.nick = "FldMinMax"; d.category = kCat; d.subcategory = "Statistics";
    d.description = "The smallest and the largest of a list of numbers (one group; Group ID is not modelled). An empty list is flagged.";
    d.inputs = {In("Value", Kind::Number, Access::List)};
    d.outputs = {Out("Min", Kind::Number), Out("Max", Kind::Number)};
    d.eval = [](EvalContext& c) {
      const std::vector<double> x = Numbers(c.List(0));
      if (x.empty()) { c.Fail("Field Min & Max needs at least one number"); return; }
      const Stats s = Compute(x);
      c.Out(0, Value::Number(s.mn)); c.Out(1, Value::Number(s.mx));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Field Variance"; d.nick = "FldVar"; d.category = kCat; d.subcategory = "Statistics";
    d.description = "Standard Deviation and Variance of a list of numbers (one group; Group ID is not modelled): Variance is the mean of the squared distances from the mean (over n, not n - 1) and Standard Deviation its square root. An empty list is flagged.";
    d.inputs = {In("Value", Kind::Number, Access::List)};
    d.outputs = {Out("Standard Deviation", Kind::Number), Out("Variance", Kind::Number)};
    d.eval = [](EvalContext& c) {
      const std::vector<double> x = Numbers(c.List(0));
      if (x.empty()) { c.Fail("Field Variance needs at least one number"); return; }
      const Stats s = Compute(x);
      c.Out(0, Value::Number(s.sd)); c.Out(1, Value::Number(s.var));
    };
    r.Add(d);
  }
}

