    NodeDef d; d.name = "Bezier Segment"; d.nick = "BezSeg"; d.category = kCat; d.subcategory = "Curve Primitives";
    d.description = "An open poly spline sampling the cubic Bezier curve from Start to End with control points Start Handle and End Handle: Resolution edges, Resolution + 1 points B(t) = (1-t)^3 Start + 3 (1-t)^2 t Start Handle + 3 (1-t) t^2 End Handle + t^3 End at t = i / Resolution. Resolution is limited to 1..10000.";
