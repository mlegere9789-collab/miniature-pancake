def scalebyplane():
    def sbp(O, n, fx, fy, f):
        n = unit(n); X = (1, 0, 0)
        x = sub(X, mul(n, dot(X, n)))
        if norm(x) < 1e-12:
            Y = (0, 1, 0); x = sub(Y, mul(n, dot(Y, n)))
        x = unit(x); y = unit(cross(n, x))
        def fn(p):
            d = sub(p, O)
            return add(O, add(add(mul(x, fx * dot(d, x)), mul(y, fy * dot(d, y))), mul(n, f * dot(d, n))))
        return fn
    cases = []
