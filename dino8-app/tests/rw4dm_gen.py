def sens_lines():
    return ["New", "SetActiveViewport Top", "RW4BEGIN_sensitivity", "Point 1,2,3.000001", "SelAll", "Move 1,2,3 0,0,0", "SelAll", "List"]

class Case:
    def __init__(self, name, desc, fixture, cmds, expected, pre=None):
        self.name, self.desc, self.fixture, self.cmds, self.expected, self.pre = name, desc, fixture, cmds, expected, pre or []

def verify_lines(expected):
    """Residual phase for the expected final object list (ids 1..n in document order). Returns (script lines, number of points listed, box strings)."""
    lines = []
    n = len(expected)
    npts = sum(1 for o in expected if o.kind == "pt")
    nid = n + 1
    points = []                    # (id, expected position)
    for k, o in enumerate(expected, 1):
        if o.kind == "pt": points.append((k, o.pts[0]))
        elif o.kind in ("line", "plane", "mesh", "poly"):
            lines += ["SelNone", "SelID %d" % k, "ExtractPt"]
            for p in o.pts:
                points.append((nid, p)); nid += 1
    for pid, p in points:
        lines += ["SelNone", "SelID %d" % pid, "Move %s 0,0,0" % fmt(p)]
    if points: lines += ["SelNone", "SelPt", "List"]   # List with nothing selected would wait for a selection and swallow the next lines
    boxes = []
    for k, o in enumerate(expected, 1):
        if o.kind != "box": continue
        lo, hi = bbox(o)
        lines += ["SelNone", "SelID %d" % k, "Move %s 0,0,0" % fmt(lo), "BoundingBox"]
        boxes.append("min 0,0,0 max %s" % ",".join(fnum(hi[i] - lo[i]) for i in range(3)))
    return lines, len(points), ";".join(boxes)

def case_lines(cs, sens=False):
    out = ["New", "SetActiveViewport Top", "RW4BEGIN_" + cs.name]
    out += [create_cmd(o) for o in cs.fixture]
    out += cs.pre
    out += ["SelNone", "SelAll"] if not any(c == "@NOSEL" for c in cs.cmds) else []
    out += [c for c in cs.cmds if c != "@NOSEL"]
    v, npts, boxes = verify_lines(cs.expected)
    out += v
    return out, npts, boxes

def build_xform(section, title, rows, cases, split=False):
    lo = section; up = section.upper()
    scripts = []
    if split:
        for cs in cases:
            fn = "rw4dm_%s_%s_script.txt" % (lo, cs.name)
            lines = ["# RW4DM_%s case %s. Generated by rw4dm_gen.py; rows %s." % (up, cs.name, ", ".join(rows)), "SetActiveViewport Top"]
            lines += case_lines(cs)[0]
            if cs is cases[-1]: lines += sens_lines()
            lines += ["Check"]
            open(os.path.join(HERE, fn), "w").write("\n".join(lines) + "\n"); scripts.append(fn)
    else:
        fn = "rw4dm_%s_script.txt" % lo
        lines = ["# RW4DM_%s: %s. Generated by rw4dm_gen.py; rows %s." % (up, title, ", ".join(rows)), "SetActiveViewport Top"]
        for cs in cases: lines += case_lines(cs)[0]
        lines += sens_lines() + ["Check"]
        open(os.path.join(HERE, fn), "w").write("\n".join(lines) + "\n"); scripts.append(fn)
    sh = SHEAD.replace("@UP@", up).replace("@LO@", lo).replace("@TITLE@", title).replace("@SCRIPTS@", "The script" + ("s are" if len(scripts) > 1 else " is") + " " + ", ".join(scripts) + ";")
    sh = sh.replace("@RUNS@", "\n".join("rw4_%s_run %s" % (lo, s) for s in scripts))
    for cs in cases:
        _, npts, boxes = case_lines(cs)
        sh += 'rw4_%s_resid %s %d "%s" "%s"\n' % (lo, cs.name, npts, boxes, cs.desc.replace('"', "'"))
    sh += SENS.replace("@UP@", up).replace("@LO@", lo)
    open(os.path.join(SECT, "96_rw4dm_%s.sh" % lo), "w").write(sh)

