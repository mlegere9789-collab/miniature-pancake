#!/usr/bin/env python3
"""Wave 4 batch: generates the RW4DM_ app test sections (sections/96_rw4dm_*.sh) and their scripts (rw4dm_*_script.txt).

Unlike rwdm_gen.py (Point objects only) every geometric case here mixes object kinds: a Point, a Line (curve), a Plane (surface) and a Box
(closed polysurface). The expected image of every object is computed HERE from the textbook closed form of the operation, never by the app.

How an image is compared (all residuals, so a pass means agreement to 1e-9, absolute; models are about 10 units):
  * Point: the point is moved from its expected image E to the origin (`Move E 0,0,0`, E typed with 17 significant digits) and listed. The app
    prints a coordinate within 1e-9 of an integer as that integer, so a residual of 0 prints "0,0,0" and a residual of 1e-6 prints "1e-06".
  * Curve / surface: `ExtractPt` turns the control points into Point objects (an affine map moves a NURBS object's control points to the
    images of the control points, so the images of the control points are the exact image of the object); each one gets the same residual test.
  * Closed solid (Box): the axis-aligned box is moved so that the expected image of its bounding-box minimum corner lands on the origin and
    `BoundingBox` must report "min 0,0,0 max <expected size>" (images of boxes are kept axis aligned: multiples of 90 degrees, translations, scales).
A negative control (a point 1e-6 off its expected image) must read "1e-06", so the harness can see an error of that size.

The logic sections (groups, layers, locks, names) use exact set / string logic on four objects: ids 1..4 = Point, Line, Plane, Box.
Run:  python3 rw4dm_gen.py   (rewrites the files next to it; the generated files are the ones committed)
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
SECT = os.path.join(HERE, "sections")

# ---------------------------------------------------------------------------------------------------------------- vector helpers
def add(a, b): return tuple(x + y for x, y in zip(a, b))
def sub(a, b): return tuple(x - y for x, y in zip(a, b))
def mul(a, s): return tuple(x * s for x in a)
def dot(a, b): return sum(x * y for x, y in zip(a, b))
def cross(a, b): return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])
def norm(a): return math.sqrt(dot(a, a))
def unit(a): n = norm(a); return mul(a, 1.0 / n)

def rodrigues(p, c, axis, deg):
    k = unit(axis); t = math.radians(deg); v = sub(p, c)
    r = add(add(mul(v, math.cos(t)), mul(cross(k, v), math.sin(t))), mul(k, dot(k, v) * (1 - math.cos(t))))
    return add(c, r)

def fnum(v):
    """The app's FormatNumber: within 1e-9 of an integer -> the integer, else %.4g."""
    if abs(v - round(v)) < 1e-9:
        r = round(v)
        return str(int(r)) if r != 0 else "0"
    return "%.4g" % v

def fmt(p):
    """A point typed into the command line with 17 significant digits (ints stay ints)."""
    return ",".join(str(int(x)) if x == int(x) else repr(float(x)) for x in p)

# ---------------------------------------------------------------------------------------------------------------- objects
class Obj:
    def __init__(self, kind, pts, label=""):
        self.kind, self.pts, self.label = kind, [tuple(float(x) for x in p) for p in pts], label

def Pt(x, y, z): return Obj("pt", [(x, y, z)])
def Ln(a, b): return Obj("line", [a, b])
def Pl(x0, y0, x1, y1): return Obj("plane", [(x0, y0, 0), (x1, y0, 0), (x0, y1, 0), (x1, y1, 0)])   # ExtractPt order of Plane in the Top plane (u-major grid)
def Poly(pts): return Obj("poly", pts)
def Bx(x0, y0, x1, y1, z0, h):
    lo = (min(x0, x1), min(y0, y1), z0); hi = (max(x0, x1), max(y0, y1), z0 + h)
    return Obj("box", [(a, b, c) for a in (lo[0], hi[0]) for b in (lo[1], hi[1]) for c in (lo[2], hi[2])])

def create_cmd(o):
    if o.kind == "pt": return "Point " + fmt(o.pts[0])
    if o.kind == "poly": return "Polyline " + " ".join(fmt(p) for p in o.pts) + "\nEnter"
    if o.kind == "line": return "Line %s %s" % (fmt(o.pts[0]), fmt(o.pts[1]))
    if o.kind == "plane": return "Plane %s %s" % (fmt(o.pts[0]), fmt(o.pts[3]))
    if o.kind == "box":
        lo, hi = bbox(o)
        return "Box %s %s %s" % (fmt(lo), fmt((hi[0], hi[1], lo[2])), fmt([hi[2] - lo[2]])[0:])
    raise ValueError(o.kind)

def bbox(o):
    return tuple(min(p[i] for p in o.pts) for i in range(3)), tuple(max(p[i] for p in o.pts) for i in range(3))

def image(o, f):
    return Obj(o.kind, [f(p) for p in o.pts], o.label)

def allbbox(objs):
    pts = [p for o in objs for p in o.pts]
    return tuple(min(p[i] for p in pts) for i in range(3)), tuple(max(p[i] for p in pts) for i in range(3))

