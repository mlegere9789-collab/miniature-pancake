def orient_map(r1, r2, t1, t2, scale, copy=False):
    vr, vt = sub(r2, r1), sub(t2, t1)
    s = (norm(vt) / norm(vr)) if scale else 1.0
    ur, ut = unit(vr), unit(vt)
    ax = cross(ur, ut); ang = math.degrees(math.atan2(norm(ax), dot(ur, ut)))
    if norm(ax) < 1e-12:
        # parallel / opposite directions in the Top plane: turn about z (a half turn when opposite)
        ang = 0.0 if dot(ur, ut) > 0 else 180.0; axis = (0, 0, 1)
    else:
        axis = ax
    return lambda p: add(t1, mul(sub(rodrigues(p, r1, axis, ang), r1), s))

