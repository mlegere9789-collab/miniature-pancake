def flow_map(Ab, Bb, At, Bt, stretch):
    up = (0, 0, 1)
    def frame(a, b):
        t = unit(sub(b, a)); n = sub(up, mul(t, dot(up, t))); n = unit(n); return t, n, cross(t, n)
    tb, nb, bb = frame(Ab, Bb); tt, nt, bt = frame(At, Bt)
    Lb, Lt = norm(sub(Bb, Ab)), norm(sub(Bt, At))
    def fn(p):
        d = dot(sub(p, Ab), tb); s = min(1.0, max(0.0, d / Lb))
        foot = add(Ab, mul(tb, s * Lb)); off = sub(p, foot)
        lx, ly, lz = dot(off, tb), dot(off, nb), dot(off, bb)
        if stretch: dist = s * Lt
        else: dist = min(s * Lb, Lt)
        return add(add(add(At, mul(tt, dist + lx)), mul(nt, ly)), mul(bt, lz))
    return fn

