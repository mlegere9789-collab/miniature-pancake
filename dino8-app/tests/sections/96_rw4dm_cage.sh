# RW4DM_CAGE: Cage, CageEdit, ExtractOriginalCaptives, ReleaseFromCage: Bezier-volume free-form deformation. The scripts are rw4dm_cage_geometry_script.txt, rw4dm_cage_identity_script.txt, rw4dm_cage_deform_script.txt, rw4dm_cage_original_script.txt, rw4dm_cage_release_script.txt; generated by rw4dm_gen.py (the closed forms are in that file). Every object kind of the case (Point, Line, Plane, Box) is
# compared with the closed-form image of the operation: points by the residual move to the origin (printed 0,0,0 within 1e-9), curve / surface control points
# through ExtractPt the same way, boxes by their bounding box after a residual move. RW4DM_CAGE_sensitivity shows that a 1e-6 error would read 1e-06.
RW4_CAGE_OUT=""
rw4_cage_run() {
  local o
  if [ -n "${DISPLAY:-}" ] && xset q >/dev/null 2>&1 || ! command -v xvfb-run >/dev/null 2>&1; then
    o="$(timeout 900 "$BIN" --smoke 60 --script "$HERE/$1" 2>&1)" || { echo "$o" | tail -40; echo "FAIL RW4DM_CAGE_run: $1 exited non-zero"; fail=1; o=""; }
  else
    o="$(timeout 900 xvfb-run -a -s "-screen 0 1600x900x24" "$BIN" --smoke 60 --script "$HERE/$1" 2>&1)" || { echo "$o" | tail -40; echo "FAIL RW4DM_CAGE_run: $1 exited non-zero"; fail=1; o=""; }
  fi
  RW4_CAGE_OUT+="$o"$'\n'
}
rw4_cage_run rw4dm_cage_geometry_script.txt
rw4_cage_run rw4dm_cage_identity_script.txt
rw4_cage_run rw4dm_cage_deform_script.txt
rw4_cage_run rw4dm_cage_original_script.txt
rw4_cage_run rw4dm_cage_release_script.txt
rw4_cage_block() { awk -v name="$1" '$0 ~ ("Unknown command: RW4BEGIN_" name "$") { on = 1; next } on && /Unknown command: RW4BEGIN_/ { exit } on { print }' <<<"$RW4_CAGE_OUT"; }
# rw4_cage_resid NAME NPTS BOXES DESC: the case listed exactly NPTS points, every one at residual 0,0,0, and the boxes' bounding boxes (joined by ';') read exactly BOXES
rw4_cage_resid() {
  local blk npts zeros boxes; blk="$(rw4_cage_block "$1")"
  npts="$({ grep -cE '^history: Object [0-9]+ \(point\)' <<<"$blk" || true; })"
  zeros="$({ grep -cE '^history:   0,0,0$' <<<"$blk" || true; })"
  boxes="$({ grep -E '^history: Bounding box min ' <<<"$blk" || true; } | sed -E 's/^history: Bounding box //' | paste -sd';' -)"
  if [ "$npts" = "$2" ] && [ "$zeros" = "$2" ] && [ "$boxes" = "$3" ]; then echo "ok   RW4DM_CAGE_$1: $4 ($2 points at residual 0 within 1e-9; boxes: ${3:-none})"
  else echo "FAIL RW4DM_CAGE_$1: $4 (listed $npts points, $zeros at residual 0, expected $2 and $2; boxes '$boxes', expected '$3')"; fail=1; { grep -E '^history:   |^history: Bounding box|^history: ! ' <<<"$blk" || true; } | head -16 | sed 's/^/     residual: /'; fi
}
rw4_cage_resid geometry 24 "" "Cage 0,0,0 6,4,0 height 2 with XDivisions=3 YDivisions=2 ZDivisions=1 is a lattice of 4 x 3 x 2 = 24 control points at i*2, j*2, k*2 (ExtractPt of the cage mesh)"
rw4_cage_resid identity 34 "" "CageEdit binds a Point, a Line and a Plane inside a 2 x 2 x 2 cage; the undeformed cage leaves all three exactly where they are"
rw4_cage_resid deform 34 "" "Moving the 9 lattice points of the face x = 4 to x = 6 deforms the captives by the Bezier-volume map x' = 4s + 2s^2 (s = x / 4), y and z unchanged (Point, Line control points, Plane control points)"
rw4_cage_resid original 41 "" "ExtractOriginalCaptives after the deformation adds exact copies of the three captives as they were before it (ids 5, 6, 7)"
rw4_cage_resid release 34 "" "ReleaseFromCage frees the three captives: moving the face x = 4 on to x = 9 afterwards leaves them at their first deformed positions"
# negative control: the same harness must SEE a 1e-6 error (a point 1e-6 off its expected image reads 1e-06, not 0)
rw4_cage_sens() {
  local blk; blk="$(rw4_cage_block sensitivity)"
  if grep -qE '^history:   (0,0,)?[-0-9.e]*1e-06' <<<"$blk" && ! grep -qE '^history:   0,0,0$' <<<"$blk"; then echo "ok   RW4DM_CAGE_sensitivity: the residual harness reports a 1e-6 error as 1e-06 (negative control)"
  else echo "FAIL RW4DM_CAGE_sensitivity: a 1e-6 error was not visible"; fail=1; { grep -E '^history:   ' <<<"$blk" || true; } | head -4 | sed 's/^/     residual: /'; fi
}
