# ---------------------------------------------------------------------------------------------------------------- RW4DM_CAGE
def lattice(origin, sizes, divs):
    nx, ny, nz = divs
    return [(origin[0] + sizes[0] * i / nx, origin[1] + sizes[1] * j / ny, origin[2] + sizes[2] * k / nz) for k in range(nz + 1) for j in range(ny + 1) for i in range(nx + 1)]

def bern(n, i, t):
    from math import comb
    return comb(n, i) * t ** i * (1 - t) ** (n - i)

def ffd(lat, divs, origin, sizes):
    """Bezier-volume free-form deformation (Sederberg and Parry 1986): the point with lattice coordinates (s,t,u) of the UNDEFORMED box
    goes to the Bernstein-weighted sum of the lattice points; the undeformed box is axis aligned with the given origin and sizes."""
    nx, ny, nz = divs
    def fn(p):
        s, t, u = ((p[0] - origin[0]) / sizes[0], (p[1] - origin[1]) / sizes[1], (p[2] - origin[2]) / sizes[2])
        out = (0.0, 0.0, 0.0)
        for k in range(nz + 1):
            for j in range(ny + 1):
                for i in range(nx + 1):
                    w = bern(nx, i, s) * bern(ny, j, t) * bern(nz, k, u)
                    out = add(out, mul(lat[i + (nx + 1) * (j + (ny + 1) * k)], w))
        return out
    return fn

def cage():
    P0 = [Pt(1, 1, 1), Ln((0.5, 0.5, 0.5), (3, 2, 3.5)), Pl(1, 1, 3, 3)]
    origin, sizes, divs = (0, 0, 0), (4, 4, 4), (2, 2, 2)
    lat0 = lattice(origin, sizes, divs)
    lat1 = [((6.0 if p[0] == 4 else p[0]), p[1], p[2]) for p in lat0]
    f = ffd(lat1, divs, origin, sizes)
    D = [image(o, f) for o in P0]
    bind = ["Cage 0,0,0 4,4,0 4", "SelNone", "SelID 1 2 3", "CageEdit", "SelID 4", "Enter"]
    pull = ["SelNone", "SelID 4", "PointsOn", "SelControlPointRegion 3.5,-1,-1 4.5,5,1", "SetPt SetX=Yes X=6 SetZ=No"]
    cases = [
        Case("geometry", "Cage 0,0,0 6,4,0 height 2 with XDivisions=3 YDivisions=2 ZDivisions=1 is a lattice of 4 x 3 x 2 = 24 control points at i*2, j*2, k*2 (ExtractPt of the cage mesh)", [],
             ["@NOSEL", "Cage XDivisions=3 YDivisions=2 ZDivisions=1 0,0,0 6,4,0 2"], [Obj("mesh", lattice((0, 0, 0), (6, 4, 2), (3, 2, 1)))]),
        Case("identity", "CageEdit binds a Point, a Line and a Plane inside a 2 x 2 x 2 cage; the undeformed cage leaves all three exactly where they are", P0,
             ["@NOSEL"] + bind, P0 + [Obj("mesh", lat0)]),
        Case("deform", "Moving the 9 lattice points of the face x = 4 to x = 6 deforms the captives by the Bezier-volume map x' = 4s + 2s^2 (s = x / 4), y and z unchanged (Point, Line control points, Plane control points)", P0,
             ["@NOSEL"] + bind + pull, D + [Obj("mesh", lat1)]),
        Case("original", "ExtractOriginalCaptives after the deformation adds exact copies of the three captives as they were before it (ids 5, 6, 7)", P0,
             ["@NOSEL"] + bind + pull + ["SelNone", "SelID 1 2 3", "ExtractOriginalCaptives"], D + [Obj("mesh", lat1)] + P0),
    ]
    lat2 = [((9.0 if p[0] == 4 else p[0]), p[1], p[2]) for p in lat0]
    cases.append(Case("release", "ReleaseFromCage frees the three captives: moving the face x = 4 on to x = 9 afterwards leaves them at their first deformed positions", P0,
                      ["@NOSEL"] + bind + pull + ["SelNone", "SelID 1 2 3", "ReleaseFromCage", "SelNone", "SelID 4", "SelControlPointRegion 5.5,-1,-1 6.5,5,1", "SetPt SetX=Yes X=9 SetZ=No"], D + [Obj("mesh", lat2)]))
    build_xform("cage", "Cage, CageEdit, ExtractOriginalCaptives, ReleaseFromCage: Bezier-volume free-form deformation", ["D8-RHINO-XFORM-0011", "D8-RHINO-XFORM-0012", "D8-RHINO-XFORM-0018", "D8-RHINO-XFORM-0047"], cases, split=True)

