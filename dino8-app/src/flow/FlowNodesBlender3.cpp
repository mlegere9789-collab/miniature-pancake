void AddMeshOps3() {
  Registry& r = Registry::Get();
  {
    NodeDef d; d.name = "Split Edges"; d.nick = "SplitEdge"; d.category = kCat; d.subcategory = "Mesh";
    d.description = "Cuts every face loose from its neighbours: each face gets its own copy of its vertices (an n-gon stays one face), so the mesh falls apart into separate faces; an edge with no face becomes two vertices of its own. Selection false changes nothing.";
    d.inputs = {In("Mesh", Kind::Mesh), In("Selection", Kind::Boolean, Access::Item, Value::Boolean(true))};
    d.outputs = {Out("Mesh", Kind::Mesh)};
    d.eval = [](EvalContext& c) {
      const kernel::Mesh* m = MeshOf(c.In(0));
      if (!m) { c.Fail("Split Edges needs a mesh"); return; }
      if (!c.Bool(1, true)) { c.Out(0, Value::MeshV(*m)); return; }
      const MD d0 = ReadMesh(m->raw());
      // the triangles of one n-gon share their vertices inside the n-gon, so a whole n-gon gets one set of copies
      std::vector<int> group(d0.f.size(), -1);
      for (size_t g = 0; g < d0.ng.size(); ++g) for (int fi : d0.ng[g]) group[static_cast<size_t>(fi)] = static_cast<int>(g);
      std::vector<std::map<int, int>> copy(d0.ng.size());
      MD out;
      for (size_t i = 0; i < d0.f.size(); ++i) {
        const auto& f = d0.f[i];
        const int k = IsWire(f) ? 2 : (IsTri(f) ? 3 : 4);
        std::array<int, 4> nf{};
        for (int e = 0; e < k; ++e) {
          const int ov = f[static_cast<size_t>(e)];
          if (group[i] >= 0) {
            auto& mp = copy[static_cast<size_t>(group[i])];
            auto it = mp.find(ov);
            if (it == mp.end()) { out.v.push_back(d0.v[static_cast<size_t>(ov)]); it = mp.emplace(ov, static_cast<int>(out.v.size()) - 1).first; }
            nf[static_cast<size_t>(e)] = it->second;
          } else { out.v.push_back(d0.v[static_cast<size_t>(ov)]); nf[static_cast<size_t>(e)] = static_cast<int>(out.v.size()) - 1; }
        }
        if (k == 2) nf = {nf[0], nf[1], nf[1], nf[1]}; else if (k == 3) nf[3] = nf[2];
        out.f.push_back(nf);
      }
      out.ng = d0.ng;
      c.Out(0, Value::MeshV(BuildMD(out)));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Subdivision Surface"; d.nick = "SubdSurf"; d.category = kCat; d.subcategory = "Mesh";
    d.description = "Catmull-Clark subdivision, Level times: every face gets a point at its centre, every edge a point (the average of its two ends and the two face centres next to it, or its midpoint on a boundary), and every old vertex moves to (Q + 2R + (n - 3) P) / n (Q the mean of the centres of its faces, R the mean of the midpoints of its edges, n its valence, P where it was; a boundary vertex with two boundary edges to (6 P + A + B) / 8). Each face of k corners becomes k quads: V' = V + E + F, E' = 2E + corners, F' = corners. Edges with no face are flagged. Level is limited to 0..4.";
    d.inputs = {In("Mesh", Kind::Mesh), In("Level", Kind::Integer, Access::Item, Value::Integer(1))};
    d.outputs = {Out("Mesh", Kind::Mesh)};
    d.eval = [](EvalContext& c) {
      const kernel::Mesh* m = MeshOf(c.In(0));
      if (!m) { c.Fail("Subdivision Surface needs a mesh"); return; }
      MD d0 = ReadMesh(m->raw());
      std::vector<std::vector<int>> rings; bool wire = false;
      if (!PolygonRings(d0, rings, wire) || rings.empty()) { c.Fail("Subdivision Surface could not read the faces of the mesh"); return; }
      if (wire) { c.Fail("Subdivision Surface does not support edges with no face"); return; }
      std::vector<Point3d> v = d0.v;
      const int level = ClampInt(c.Int(1, 1), 0, 4);
      for (int s = 0; s < level; ++s) {
        const size_t nv = v.size(), nf = rings.size();
        std::vector<Point3d> fp(nf);
        for (size_t p = 0; p < nf; ++p) {
          double x = 0, y = 0, z = 0;
          for (int i : rings[p]) { x += v[static_cast<size_t>(i)].x; y += v[static_cast<size_t>(i)].y; z += v[static_cast<size_t>(i)].z; }
          const double k = static_cast<double>(rings[p].size());
          fp[p] = Point3d(x / k, y / k, z / k);
        }
        std::map<std::pair<int, int>, std::vector<int>> adj;  // edge -> faces
        for (size_t p = 0; p < nf; ++p) for (size_t i = 0; i < rings[p].size(); ++i) {
          const int a = rings[p][i], b = rings[p][(i + 1) % rings[p].size()];
          adj[{std::min(a, b), std::max(a, b)}].push_back(static_cast<int>(p));
        }
        std::map<std::pair<int, int>, int> eid;
        std::vector<Point3d> ep, mid;
        for (const auto& kv : adj) {
          const Point3d& a = v[static_cast<size_t>(kv.first.first)]; const Point3d& b = v[static_cast<size_t>(kv.first.second)];
          const Point3d mp((a.x + b.x) / 2, (a.y + b.y) / 2, (a.z + b.z) / 2);
          mid.push_back(mp);
          if (kv.second.size() == 2) {
            const Point3d& f1 = fp[static_cast<size_t>(kv.second[0])]; const Point3d& f2 = fp[static_cast<size_t>(kv.second[1])];
            ep.push_back(Point3d((a.x + b.x + f1.x + f2.x) / 4, (a.y + b.y + f1.y + f2.y) / 4, (a.z + b.z + f1.z + f2.z) / 4));
          } else ep.push_back(mp);
          eid[kv.first] = static_cast<int>(eid.size());
        }
        std::vector<Point3d> nvp = v;
        for (size_t i = 0; i < nv; ++i) {
          std::vector<int> faces; std::vector<std::pair<int, int>> edges;
          for (size_t p = 0; p < nf; ++p) if (std::find(rings[p].begin(), rings[p].end(), static_cast<int>(i)) != rings[p].end()) faces.push_back(static_cast<int>(p));
          for (const auto& kv : adj) if (kv.first.first == static_cast<int>(i) || kv.first.second == static_cast<int>(i)) edges.push_back(kv.first);
          if (faces.empty()) continue;
          std::vector<std::pair<int, int>> boundary;
          bool manifold = true;
          for (const auto& e : edges) { const size_t k = adj[e].size(); if (k == 1) boundary.push_back(e); else if (k != 2) manifold = false; }
          if (!manifold) continue;
          const Point3d& P = v[i];
          if (!boundary.empty()) {
            if (boundary.size() != 2) continue;
            const int a = boundary[0].first == static_cast<int>(i) ? boundary[0].second : boundary[0].first;
            const int b = boundary[1].first == static_cast<int>(i) ? boundary[1].second : boundary[1].first;
            nvp[i] = Point3d((6 * P.x + v[static_cast<size_t>(a)].x + v[static_cast<size_t>(b)].x) / 8, (6 * P.y + v[static_cast<size_t>(a)].y + v[static_cast<size_t>(b)].y) / 8,
                             (6 * P.z + v[static_cast<size_t>(a)].z + v[static_cast<size_t>(b)].z) / 8);
            continue;
          }
          const double n = static_cast<double>(edges.size());
          Vector3d q(0, 0, 0), rr(0, 0, 0);
          for (int p : faces) q += Vector3d(fp[static_cast<size_t>(p)].x, fp[static_cast<size_t>(p)].y, fp[static_cast<size_t>(p)].z) / static_cast<double>(faces.size());
          for (const auto& e : edges) { const Point3d& mp = mid[static_cast<size_t>(eid[e])]; rr += Vector3d(mp.x, mp.y, mp.z) / n; }
          nvp[i] = Point3d((q.x + 2 * rr.x + (n - 3) * P.x) / n, (q.y + 2 * rr.y + (n - 3) * P.y) / n, (q.z + 2 * rr.z + (n - 3) * P.z) / n);
        }
        std::vector<Point3d> all = nvp;
        const int e0 = static_cast<int>(all.size());
        all.insert(all.end(), ep.begin(), ep.end());
        const int f0 = static_cast<int>(all.size());
        all.insert(all.end(), fp.begin(), fp.end());
        std::vector<std::vector<int>> nr;
        for (size_t p = 0; p < nf; ++p) {
          const auto& ring = rings[p];
          const size_t k = ring.size();
          for (size_t i = 0; i < k; ++i) {
            const int a = ring[i], b = ring[(i + 1) % k], z = ring[(i + k - 1) % k];
            nr.push_back({a, e0 + eid[{std::min(a, b), std::max(a, b)}], f0 + static_cast<int>(p), e0 + eid[{std::min(a, z), std::max(a, z)}]});
          }
        }
        v = all; rings = nr;
      }
      MB mb;
      for (const Point3d& p : v) mb.V(p.x, p.y, p.z);
      for (const auto& ring : rings) AddRingFace(mb, ring);
      c.Out(0, Value::MeshV(mb.Build()));
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Set Position"; d.nick = "SetPos"; d.category = kCat; d.subcategory = "Geometry";
    d.description = "Moves every vertex of a mesh, point of a curve, or a point: when Position is connected each one is first put at that point, then Offset is added. Position and Offset are constants here, not fields. A curve whose points would all coincide is flagged.";
    d.inputs = {In("Geometry", Kind::Any), In("Position", Kind::Point, Access::Item, Value::Null(), true), In("Offset", Kind::Vector, Access::Item, Value::Vector(Vector3d(0, 0, 0)))};
    d.outputs = {Out("Geometry", Kind::Any)};
    d.eval = [](EvalContext& c) {
      const Value& g = c.In(0);
      const bool set = c.Has(1);
      const Point3d pos = c.Pt(1);
      const Vector3d off = c.Vec(2, Vector3d(0, 0, 0));
      auto move = [&](const Point3d& p) { return (set ? pos : p) + off; };
      if (const kernel::Mesh* m = MeshOf(g)) {
        MD d0 = ReadMesh(m->raw());
        for (Point3d& p : d0.v) p = move(p);
        c.Out(0, Value::MeshV(BuildMD(d0)));
      } else if (g.kind == Kind::Curve) {
        Poly p;
        if (!CurvePoly(g, p)) { c.Fail("Set Position could not read the curve"); return; }
        for (Point3d& q : p.pts) q = move(q);
        if (set) { c.Fail("Every point of the curve would coincide"); return; }
        c.Out(0, Value::Curve(PolyCurve(p.pts, p.closed)));
      } else if (g.kind == Kind::Point) {
        c.Out(0, Value::Point(move(g.point)));
      } else c.Fail("Set Position needs a mesh, curve or point");
    };
    r.Add(d);
  }
  {
    NodeDef d; d.name = "Points to Curves"; d.nick = "Pts2Crv"; d.category = kCat; d.subcategory = "Curve";
    d.description = "Joins points (the vertices of a mesh) into one poly spline in vertex order. Curve Group ID and Weight are not modelled, so all points form one curve; fewer than two points is flagged.";
    d.inputs = {In("Points", Kind::Mesh)};
    d.outputs = {Out("Curves", Kind::Curve)};
    d.eval = [](EvalContext& c) {
      const kernel::Mesh* m = MeshOf(c.In(0));
      if (!m) { c.Fail("Points to Curves needs points"); return; }
      const MD d0 = ReadMesh(m->raw());
      if (d0.v.size() < 2) { c.Fail("Points to Curves needs at least two points"); return; }
      c.Out(0, Value::Curve(PolyCurve(d0.v, false)));
    };
    r.Add(d);
  }
}

